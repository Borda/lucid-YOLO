"""Overfit-100 integration golden: the full train loop memorizes a fixed slice (WP-040).

The Phase-5 end-to-end integration check. A single ``n``-scale
:class:`~lit_yolo.ptl.module.DetectionLitModule` is trained on a fixed ~100-image
synthetic detection slice (generated by ``fuse-augmentations``, R21/A26) with the
real training stack wired together — the dual-branch loss, the
:class:`~lit_yolo.optim.musgd.MuSGD` optimizer, the progressive-loss ramp, and the
``close_mosaic`` schedule (disabled from epoch 0 so the fit sees a stationary
target). If that loop composes correctly the network memorizes the slice, so the
one-to-one branch's decoded detections recall essentially every ground-truth box.

The gate is **train-set recall at IoU 0.5**: after training, each image is decoded
through the NMS-free :class:`~lit_yolo.decode.topk_e2e.TopKDecoder` and every
ground truth is greedily matched, in detection-score order (COCO-style, no
confidence gate), to a same-class detection whose IoU is at least
:data:`_IOU_THRESHOLD`. Recall is the matched fraction over all instances; the DoD
floor is ``>= 0.95``.

Golden policy (cross-platform, D-golden): the frozen ``goldens/gpu/overfit_micro_det.json``
pins the integer counts (images, instances, classes, epochs, image size) **exactly**
and the achieved recall with a generous tolerance (:data:`_RECALL_TOL`) — a
regression guard against a silent drop, while the ``>= 0.95`` floor (asserted by the
test and by :func:`main`) is the actual acceptance. The golden lives under
``goldens/gpu/`` so the default offline ``scripts/check_goldens.py`` run — which
globs only top-level and ``frozen/`` goldens — never recomputes it; it is checked
only under ``check_goldens.py --include-gpu`` on a machine with an accelerator.

The model recipe (variant, optimizer/loss gains, the progressive-loss endpoints,
seed, batch size) is read from ``configs/overfit_100.yaml`` so that file stays the
single source of truth. The image size (:data:`_IMG_SIZE`), the epoch budget
(:data:`_EPOCHS`, tuned above the recipe's documented 40 to clear the floor from
scratch), and the gradient clip (:data:`_GRAD_CLIP`, standing in for the deferred-A8
LR warmup) are this script's constants — all documented as proposed assumptions
(A-overfit-imgsz / A-overfit-epochs / A-overfit-clip).

Provenance: blueprint sec. 5.8-5.11, R1 Eq. 2-3. Assumptions: A8, A26.
"""

